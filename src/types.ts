  companyId?: string;
  location?: string;
  industry?: string;
  headline?: string;
  skills?: string[];
  profileCompleted?: boolean;
  profileCompletionPercentage?: number;
  plan?: string;
  subscriptionName?: string;
  subscriptionStatus?: string;
  subscriptionExpiresAt?: string;
  lastLoginAt?: string;
